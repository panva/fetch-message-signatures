// Refreshes the vendored copy of the httpwg/structured-field-tests conformance corpus that
// test/structured-fields.ts runs against.
//
//   node --run fixtures            refresh from the default branch
//   node --run fixtures -- <ref>   refresh from a branch, tag, or commit
//
// The corpus is vendored rather than fetched at test time so that the test suite stays offline,
// deterministic, and reviewable: a corpus update shows up as a diff, and the exact upstream commit
// it came from is recorded in metadata.json.
//
// Importing this module instead of running it exposes writeCorpusIndex() without cloning anything,
// which is how the generated index is rebuilt from an already-vendored corpus.

import { execFileSync } from 'node:child_process'
import { cpSync, mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPOSITORY = 'https://github.com/httpwg/structured-field-tests.git'
const TARGET = fileURLToPath(new URL('./test/fixtures/structured-field-tests', import.meta.url))
const INDEX = fileURLToPath(new URL('./test/fixtures/corpus.ts', import.meta.url))

/**
 * Emits test/fixtures/corpus.ts, which imports every vendored fixture as a JSON module.
 *
 * The suite loads the corpus through this module rather than reading the directory at run time, so
 * that one set of test files runs unchanged on Node.js, Deno, and Bun and, once bundled, in
 * browsers and Cloudflare Workers, none of which have a filesystem. It also keeps the fixture list
 * an explicit, reviewable diff.
 */
export function writeCorpusIndex() {
  const fixtures = (directory) =>
    readdirSync(join(TARGET, directory))
      .filter((name) => name.endsWith('.json') && name !== 'metadata.json')
      .sort()
      .map((name) => (directory === '' ? name : `${directory}/${name}`))

  const parse = fixtures('')
  const serialisation = fixtures('serialisation-tests')
  const identifier = (path) => `f_${path.replace(/[^a-zA-Z0-9]/g, '_')}`
  const group = (name, list) =>
    [
      `export const ${name}: ReadonlyArray<readonly [name: string, cases: ReadonlyArray<unknown>]> = [`,
      ...list.map((path) => `  ['${path}', ${identifier(path)}],`),
      ']',
    ].join('\n')

  writeFileSync(
    INDEX,
    [
      '// Generated by `node --run fixtures`. Do not edit.',
      '//',
      '// Imports the vendored httpwg/structured-field-tests corpus as JSON modules, so that the test',
      '// suite needs no filesystem and runs unchanged in every target runtime.',
      '',
      "import metadata from './structured-field-tests/metadata.json' with { type: 'json' }",
      ...[...parse, ...serialisation].map(
        (path) =>
          `import ${identifier(path)} from './structured-field-tests/${path}' with { type: 'json' }`,
      ),
      '',
      'export const CORPUS_METADATA = metadata as {',
      '  readonly repository: string',
      '  readonly commit: string',
      '  readonly committed: string',
      '  readonly files: number',
      '}',
      '',
      group('PARSE_FIXTURES', parse),
      '',
      group('SERIALISATION_FIXTURES', serialisation),
      '',
    ].join('\n'),
  )

  return parse.length + serialisation.length
}

if (import.meta.filename === process.argv[1]) {
  const ref = process.argv[2]
  const checkout = mkdtempSync(join(tmpdir(), 'structured-field-tests-'))

  const git = (...args) =>
    execFileSync('git', ['-C', checkout, ...args], { encoding: 'utf8' }).trim()

  try {
    execFileSync('git', ['clone', '--quiet', '--depth', '1', REPOSITORY, checkout], {
      stdio: ['ignore', 'ignore', 'inherit'],
    })
    if (ref !== undefined) {
      git('fetch', '--quiet', '--depth', '1', 'origin', ref)
      git('checkout', '--quiet', '--detach', 'FETCH_HEAD')
    }

    // Everything the suite reads, plus the upstream license that covers the vendored files. The
    // schema directory describes the fixture format and is not itself a fixture.
    const paths = git('ls-files')
      .split('\n')
      .filter(
        (path) => (path.endsWith('.json') && !path.startsWith('schema/')) || path === 'LICENSE.md',
      )
    if (paths.length === 0) {
      throw new Error('No fixtures found in the upstream checkout')
    }

    rmSync(TARGET, { recursive: true, force: true })
    for (const path of paths) {
      const destination = join(TARGET, path)
      mkdirSync(join(destination, '..'), { recursive: true })
      cpSync(join(checkout, path), destination)
    }

    // Only values that are fixed for a given commit are recorded, so re-running against the same ref
    // produces no diff.
    writeFileSync(
      join(TARGET, 'metadata.json'),
      `${JSON.stringify(
        {
          repository: REPOSITORY,
          commit: git('rev-parse', 'HEAD'),
          committed: git('log', '-1', '--format=%cI'),
          files: paths.length,
        },
        null,
        2,
      )}\n`,
    )

    const indexed = writeCorpusIndex()

    console.log(
      `Vendored ${paths.length} files into ${relative(process.cwd(), TARGET)} and indexed ${indexed} fixtures in ${relative(process.cwd(), INDEX)}`,
    )
  } finally {
    rmSync(checkout, { recursive: true, force: true })
  }
}
